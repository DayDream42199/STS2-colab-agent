"""
Card model + a starting card pool.

Cards are data + a resolve() callback, same design as before, but now:
- Cards carry `values` (base numbers) and `upgrade_values` (overrides once
  upgraded), matching how the real STS2 card data is structured
  (base_text / upgraded_text / a numeric diff). Effects read numbers via
  `card.val("key")` instead of hardcoding them, so upgrading a card doesn't
  require a different effect function.
- `cost` can be an int OR the string "X" (spend-all-energy cards like
  Whirlwind/Cascade). combat.py resolves "X" into an actual spent amount
  and passes it to the effect as `x_amount`.
- Effect signature is now `(engine, caster, target, card, **kwargs)` --
  the trailing `card` lets effects read their own values/upgrade state,
  and `**kwargs` carries things like `x_amount` that only some cards need.

Coop cards were rewritten to match confirmed real STS2 design (cards that
directly buff/support an ally) rather than the earlier invented "read the
ally's state for a bonus" pattern.
"""

from dataclasses import dataclass, field
from enum import Enum, auto
from typing import Callable, Dict, List, Optional, Union
import copy

from .entities import HAND_LIMIT
from .statuses import StatusType, DEBUFF_STATUSES


class CardType(Enum):
    ATTACK = auto()
    SKILL = auto()
    POWER = auto()
    STATUS = auto()   # Wound, etc. -- unplayable, never appears in the pool/rewards
    CURSE = auto()    # Ascender's Bane, Injury, ... -- same, but a separate
                      # type in the data and separately rewarded/removed


# Cost used for "$Unplayable" cards. The wiki encodes these as Cost = -2;
# a large positive number instead means the ordinary affordability check in
# playable_cards/play_card rejects them with no special case, and no cost
# reduction can accidentally make one castable. Named because it was an
# unexplained 999 literal at ~20 call sites.
UNPLAYABLE = 999


class TargetMode(Enum):
    SINGLE_ENEMY = auto()
    ALL_ENEMIES = auto()
    SELF = auto()
    ALLY = auto()          # coop: targets one other player
    SELF_OR_ALLY = auto()  # coop: caster chooses


# Card rarity, from the wiki's Ironclad card list. Kept as name sets rather
# than a per-entry argument on all 67 pool entries: one table is far easier
# to audit against the wiki than 67 scattered literals, and it also covers
# cards built outside the pool (starter decks, make_wound()-style one-offs).
# Anything in the pool that isn't listed here is Uncommon, which is the
# largest tier -- _assert_rarity_coverage() below checks that assumption
# still holds so a future card can't silently default into the wrong tier.
