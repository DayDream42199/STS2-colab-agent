    this_card = card

    def _on_turn_end(engine, player, **kw):
        if this_card not in player.exhaust_pile:
            return
        engine.auto_play_card(player, this_card, source="Howl from Beyond",
                              from_exhaust=True)
    _arm_once(caster, card, "turn_end", _on_turn_end)


