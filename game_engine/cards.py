def fx_grapple(engine, caster, target, card, **kwargs):
    """Deal damage. Whenever you gain Block this turn, deal N damage to the
    enemy. The follow-up damage is locked to the enemy this card hit; if it
    dies, the trigger retargets to any living enemy rather than fizzling."""
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    follow_up = card.val("followup")
    victim = target

    def _on_block_gained(engine, player, **kw):
        enemy = victim if victim.alive else None
        if enemy is None:
            alive = engine.enemies_alive()
