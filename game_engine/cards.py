def fx_pillage(engine, caster, target, card, **kwargs):
    """Draw cards until a non-Attack is drawn. Terminates safely even
    against an all-Attack deck: draw_cards() itself stops once both the
    draw and discard piles are empty (or no_more_draw_this_turn is set),
    which shows up here as hand size not growing. A FULL HAND shows up the
    same way and stops it too, which is right -- unlike Havoc, this really
    is drawing into your hand."""
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    while True:
        before = len(caster.hand)
        caster.draw_cards(1, engine.log)
        if len(caster.hand) <= before:
            break
        if caster.hand[-1].card_type != CardType.ATTACK:
            break


def fx_rampage(engine, caster, target, card, **kwargs):
    """Deal damage (base + this instance's accumulated bonus), then grow
    that bonus for the rest of this combat. See Card.combat_bonus_damage's
    docstring for why this needs its own field instead of mutating
    `values` or reusing `upgraded`."""
    dmg = caster.deal_attack_damage(card.val("damage") + card.combat_bonus_damage)
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    card.combat_bonus_damage += card.val("increase")
    engine.log.append(f"{card.name}'s damage increases by {card.val('increase')} this combat "
                       f"(now +{card.combat_bonus_damage} total)")


