def fx_anger(engine, caster, target, card, **kwargs):
    """Deal damage. Add a copy of this card into your Discard Pile.
    (The original also returns to discard normally after play, so you end
    up with 2 copies in discard -- matches real Anger behavior.)"""
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    clone = card.clone()
    caster.discard_pile.append(clone)
    engine.log.append(f"{caster.name} adds a copy of {card.name} to discard pile")


def fx_armaments(engine, caster, target, card, **kwargs):
    """Gain Block. Upgrade a card in your Hand (upgraded: ALL cards in hand).
    No UI to choose, so base version auto-picks the first upgradable card."""
    gained = caster.gain_block(card.val("block"))
    engine.log.append(f"{caster.name} gains {gained} block ({card.name})")
    candidates = [c for c in caster.hand if not c.upgraded]
    if not candidates:
        return
    if card.upgraded:
        for c in candidates:
            caster.upgrade_for_combat(c)
        engine.log.append(f"{caster.name} upgrades all cards in hand ({card.name})")
    else:
        chosen = engine.request_choice(caster, candidates,
                                        "Upgrade a card in your Hand", "upgrade")
        caster.upgrade_for_combat(chosen)
        engine.log.append(f"{caster.name} upgrades {chosen.name} ({card.name})")


def fx_blood_wall(engine, caster, target, card, **kwargs):
    caster.lose_hp(card.val("hploss", 2), log=engine.log, label=card.name)
    caster.gain_block(card.val("block"))


def fx_body_slam(engine, caster, target, card, **kwargs):
    """Deal damage equal to your current Block."""
    dmg = caster.deal_attack_damage(caster.block)
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)


def fx_breakthrough(engine, caster, target, card, **kwargs):
    caster.lose_hp(card.val("hploss", 1), log=engine.log, label=card.name)
    for e in engine.enemies_alive():
        dmg = caster.deal_attack_damage(card.val("damage"))
        e.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)


def fx_cinder(engine, caster, target, card, **kwargs):
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    hand = [c for c in caster.hand if c is not card]
    if hand:
        engine.exhaust_card(caster, caster.rng.choice(hand))


def fx_headbutt(engine, caster, target, card, **kwargs):
    """Deal damage. Put a card from your Discard Pile on top of your Draw
    Pile. 'Top' = end of the list, matching how draw_cards() pops."""
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    if caster.discard_pile:
        chosen = engine.request_choice(caster, caster.discard_pile,
                                        "Put a card on top of your Draw Pile",
                                        "to_draw_top")
        caster.discard_pile.remove(chosen)
        caster.draw_pile.append(chosen)
        engine.log.append(f"{caster.name} puts {chosen.name} on top of the draw pile ({card.name})")


def fx_molten_fist(engine, caster, target, card, **kwargs):
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    current_vuln = target.get_status(StatusType.VULNERABLE)
    if current_vuln > 0:
        target.add_status(StatusType.VULNERABLE, current_vuln, applier=caster)
        engine.log.append(f"{target.name}'s vulnerable is doubled ({card.name})")


def fx_perfected_strike(engine, caster, target, card, **kwargs):
    """Extra damage per card containing 'Strike' in the caster's WHOLE deck
    (not just hand) -- matches real STS Perfected Strike scaling."""
    strike_count = sum(1 for c in caster.deck_template if "Strike" in c.name)
    extra = card.val("extradamage") * strike_count
    dmg = caster.deal_attack_damage(card.val("damage") + extra)
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)


def fx_pommel_strike(engine, caster, target, card, **kwargs):
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    engine.draw_extra(caster, card.val("cards"))


def fx_setup_strike(engine, caster, target, card, **kwargs):
    """Deal damage, THEN gain Strength for the rest of this turn only
    (doesn't buff this card's own damage -- matches real card text order)."""
    dmg = caster.deal_attack_damage(card.val("damage"))
    target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
    caster.add_status(StatusType.STRENGTH_THIS_TURN, card.val("strength"))


def fx_sword_boomerang(engine, caster, target, card, **kwargs):
    times = card.val("repeat")
    for _ in range(times):
        alive = engine.enemies_alive()
        if not alive:
            break
        victim = caster.rng.choice(alive)
        dmg = caster.deal_attack_damage(card.val("damage"))
        victim.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)


def fx_taunt(engine, caster, target, card, **kwargs):
    caster.gain_block(card.val("block"))
    target.add_status(StatusType.VULNERABLE, card.val("vulnerable"), applier=caster)


def fx_thunderclap(engine, caster, target, card, **kwargs):
    for e in engine.enemies_alive():
        dmg = caster.deal_attack_damage(card.val("damage"))
        e.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)
        e.add_status(StatusType.VULNERABLE, card.val("vulnerable", 1), applier=caster)


def fx_tremble(engine, caster, target, card, **kwargs):
    target.add_status(StatusType.VULNERABLE, card.val("vulnerable"), applier=caster)


def fx_twin_strike(engine, caster, target, card, **kwargs):
    for _ in range(2):
        dmg = caster.deal_attack_damage(card.val("damage"))
        target.take_damage(dmg, log=engine.log, label=card.name, attacker=caster)


def _auto_target_for(engine, caster, played):
    """Target for a card being played BY another card (Havoc, Cascade).

    Returns (resolvable, target). Not resolvable when the card needs a
    living enemy and there is none: effect functions take a live target for
    granted -- fx_spite dereferences `target.alive` on its first line -- so
    passing None crashes instead of fizzling. CombatEngine.auto_play_card
    already bails in exactly this case; these two were the outliers."""
    if played.target == TargetMode.SINGLE_ENEMY:
        alive = engine.enemies_alive()
        if not alive:
            return False, None
        return True, min(alive, key=lambda e: e.hp)
    if played.target == TargetMode.SELF:
        return True, caster
    if played.target == TargetMode.ALLY:
        return True, engine.other_player(caster)
    return True, None


def fx_havoc(engine, caster, target, card, **kwargs):
    """Play the top card of your Draw Pile and Exhaust it.

    Takes the card straight off the draw pile rather than drawing it: it
    never enters the hand in the real game, so the hand limit must not
    apply. This used to draw 1 and pop the hand, which meant a full hand
    turned Havoc into a no-op."""
    played = caster.take_top_of_draw(engine.log)
    if played is None:
        engine.log.append(f"{card.name} finds no card to play")
        return
    engine.log.append(f"{card.name} plays {played.name} from the draw pile")
    resolvable, auto_target = _auto_target_for(engine, caster, played)
    if resolvable:
        engine.resolve_card_effect(caster, played, auto_target)
    else:
        engine.log.append(f"{played.name} has nothing left to hit")
    engine.exhaust_card(caster, played)


