def _arm_power(caster, card, event, callback, expires_this_turn=False):
    """Register a Power's listener exactly once per card INSTANCE.

    Powers are normally played once, but Replay, Mayhem, Havoc and Cascade
    can each play the same instance again, and without this guard every
    replay stacks another listener -- so a twice-played Panache would deal
    its damage twice per trigger. Same failure Drum of Battle had, in card
    form; armed_card_hooks is the existing per-combat guard set."""
    key = (id(card), event)
    if key in caster.armed_card_hooks:
        return False
    caster.armed_card_hooks.add(key)
    caster.register_hook(event, callback, expires_this_turn)
    return True


