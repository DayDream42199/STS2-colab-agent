def fx_beacon_of_hope(engine, caster, target, card, **kwargs):
    """Power: "Whenever you gain Block on your turn, other players gain half
    that much Block." Guarded against re-entry -- the ally's own gain_block
    fires block_gained too, and without the guard two Beacons would bounce
    Block between players forever."""
    caster.share_block_with_allies = True
    def on_block(engine, player, amount=0, **kw):
        if getattr(player, "_beacon_busy", False):
            return
        player._beacon_busy = True
        try:
            for p in engine.players_alive():
                if p is not player:
                    p.gain_block(amount // 2, from_card=False)
        finally:
            player._beacon_busy = False
    _arm_power(caster, card, "block_gained", on_block)


