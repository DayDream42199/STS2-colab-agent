def fx_drum_of_battle(engine, caster, target, card, **kwargs):
    """Draw now. When THIS specific card instance is later Exhausted
    (Second Wind, Havoc, etc. -- not necessarily right away), gain
    Energy. Filters card_exhausted by object identity so it only fires
    for this printing, not every card the player Exhausts."""
    engine.draw_extra(caster, card.val("cards"))
    energy_amt = card.val("energy")

    # The draw happens on every play, but the "when Exhausted" listener must
    # only be armed ONCE per combat for this instance. This card returns to
    # the discard pile after each play, so it can legitimately be drawn and
    # replayed within one fight -- without this guard each replay stacked
    # another identical listener, and a single later Exhaust paid out once
    # per play (2 plays -> +4 energy instead of +2).
    if id(card) in caster.armed_card_hooks:
        return
    caster.armed_card_hooks.add(id(card))

    def _on_exhaust(engine, player, card=None, **kw):
        if card is not this_card:
            return
        player.energy += energy_amt
        engine.log.append(f"{player.name} gains {energy_amt} energy (Drum of Battle trigger)")
    this_card = card
    caster.register_hook("card_exhausted", _on_exhaust)


