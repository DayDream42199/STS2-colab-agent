# --- Status cards -----------------------------------------------------------
# Every one is Unplayable unless the wiki gives it a real cost. The effects
# live in the engine, not here: Disintegration in
# CombatEngine.END_OF_TURN_HAND_PENALTIES, Mind Rot and Waste Away in
# Player.start_turn, Sloth in CombatEngine.play_cap, Void in draw.

def _status_card(name, text, cost=UNPLAYABLE, effect=None, **kw) -> Card:
    return Card(name, cost, CardType.STATUS, TargetMode.SELF,
                effect or (lambda *a, **kw2: None),
                description=text, upgraded_description=text, **kw)


def fx_debris(engine, caster, target, card, **kwargs):
    """Debris is the odd Status out: cost 1 and its whole text is
    "$Exhaust.", so it is genuinely playable and simply burns an energy to
    get rid of itself. play_card exhausts it, since the pool entry sets
    exhausts=True."""
    engine.log.append(f"{caster.name} clears away {card.name}")


def make_debris() -> Card:
    return _status_card("Debris", "Exhaust.", cost=1, effect=fx_debris, exhausts=True)


def make_disintegration() -> Card:
    """Wiki text is "At the end of your turn, take 6/7/8 damage" -- three
    numbers on a NoUpgrade card. Investigated (#47) and NOT resolvable:

    * It is not Ascension notation. STS2 ascension scaling is written
      `{{Asc|9|21|2}}` (see the Fabricator in Module:Enemies/StS2_data/
      Glory), and "6/7/8" appears nowhere else in ANY card, power, keyword
      or enemy module -- it is a one-off with no convention behind it.
    * There is no in-game context to read it against, because NOTHING
      CREATES THIS CARD. "Disintegration" occurs in exactly one place in
      the whole wiki -- its own entry in the Colorless module. No card,
      relic, potion, event or enemy power grants it. (The Fabricator has a
      move called "Disintegrate", but that is a plain 11-damage attack and
      is unrelated.)
    * It therefore has no page of its own to check either.

    Left at 6, the lowest value, which is inert in practice: no enemy here
    generates it, exactly mirroring the data. Kept in STATUS_CARDS so the
    151-entry Colorless ledger stays complete."""
    return _status_card("Disintegration",
                        "Unplayable. At the end of your turn, take 6 damage.")


