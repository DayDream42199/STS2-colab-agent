def rarity_for_card(name: str, card_type: "CardType" = None) -> str:
    if card_type == CardType.STATUS:
        return "Status"
    if card_type == CardType.CURSE:
        return "Curse"
    if name in _BASIC_CARDS:
        return "Basic"
    if name in _COMMON_CARDS:
        return "Common"
    if name in _RARE_CARDS:
        return "Rare"
    if name in _ANCIENT_CARDS:
        return "Ancient"
    if name in _TOKEN_CARDS:
        return "Token"
    if name in _COLORLESS_CARDS:
        return "Colorless"
    return "Uncommon"


@dataclass(eq=False)
class Card:
    """eq=False: dataclass's default auto-generated __eq__ compares ALL
    fields, so two freshly-made cards with identical values (e.g. two
    Slimed cards, or two starting Strikes) would be considered `==` to
    each other. That breaks any `card in player.hand` / `list.remove(card)`
    / `list.index(card)` check throughout this codebase, all of which mean
    "this exact instance" -- found via a real bug: playing Slimed drew a
    NEW Slimed into hand, and the subsequent exhaust_card(player, card)
    call (with `card` = the ORIGINAL, already-played instance, no longer
    in hand) matched and incorrectly removed the newly-drawn one instead,
    since they compared equal. eq=False falls back to identity comparison
    (Python's default for a class with no __eq__), which is what every
    such check in this codebase actually needs."""
    name: str
    cost: Union[int, str]       # int, or the literal string "X"
    card_type: CardType
    target: TargetMode
    # effect(engine, caster, target, card, **kwargs) -> None
    effect: Callable
    values: Dict[str, int] = field(default_factory=dict)
    upgrade_values: Dict[str, int] = field(default_factory=dict)
    exhausts: bool = False
    loses_exhaust_on_upgrade: bool = False   # e.g. Demonic Shield: exhausts base, not upgraded
    upgraded: bool = False
    is_multiplayer: bool = False   # only offered/usable in coop, per real STS2 data
    upgrade_cost: Optional[int] = None   # e.g. Body Slam/Havoc/Tank/Dark Embrace: cost 1 less once upgraded
    # Per-instance, per-COMBAT bonus this specific card's damage carries
    # forward across multiple plays this fight (Rampage: "increase this
    # card's damage by 5 this combat"). Deliberately separate from
    # `values`/`upgrade_values` (the permanent base numbers) and from
    # `upgraded` (a permanent, run-long flag) -- mutating either of those
    # instead would incorrectly persist into the NEXT combat too, since
    # deck_template's Card objects are the same objects reused every
    # fight in a gauntlet run. Player.start_combat() resets this to 0 for
    # every card in deck_template at the start of each fight.
    combat_bonus_damage: int = 0
    # Basic | Common | Uncommon | Rare | Status. Left blank at construction
    # and filled by __post_init__ from RARITY_BY_NAME, so every Card gets a
    # correct rarity no matter how it's built (pool factory, starter deck,
    # or a make_wound()-style one-off) without 67 call sites repeating it.
    rarity: str = ""
    description: str = ""
    upgraded_description: str = ""
    # Innate: "start each combat with this card in your Hand." Two flags
    # because Aggression and Juggling both print Innate ONLY on the upgraded
    # side (`Text = "[|$Innate. ]..."` in the wiki data).
    innate: bool = False
    innate_on_upgrade: bool = False
    # Self-referential cost: dynamic_cost(card, player) -> int. For cards
    # whose printed cost depends on combat state at play time (Stomp: "costs
    # 1 less for each Attack played this turn"; Midnight: "costs 1 less for
    # each card Exhausted this combat by ANYONE"). Distinct from
    # `upgrade_cost`, which is a permanent, state-free change.
    dynamic_cost: Optional[Callable] = None
    # Reversible per-instance overrides, set through Player.set_temp_cost /
    # Player.grant_replay so they can be undone at the right boundary. Never
    # write these directly: a card in hand is the same object that lives in
    # deck_template, so an un-reverted write persists for the whole run.
    temp_cost: Optional[int] = None
    replay: int = 0
    # Bound (Queen's Chains of Binding): only one Bound card may be played
    # per turn. Cleared at end of turn by CombatEngine.
    bound: bool = False
    # Retain: "this card is not discarded at the end of your turn." Two
    # flags for the same reason innate has two -- Anointed, Gold Axe, Scrawl
    # and Wish all print Retain only on the upgraded side
    # (`Text = "[|$Retain.<br>]..."` in the wiki data).
    retain: bool = False
    retain_on_upgrade: bool = False
    # Ethereal: "if this is in your Hand at the end of your turn, Exhaust
    # it." Apparition is the mirror image of the Retain cards above -- it
    # prints Ethereal on the BASE side and LOSES it on upgrade
    # (`"[$Ethereal. <br>|] Gain 1 $Intangible."`) -- so this needs its own
    # loses-on-upgrade flag rather than an on_upgrade one.
    ethereal: bool = False
    loses_ethereal_on_upgrade: bool = False
    # Eternal: "cannot be removed from your Deck." Deck editing happens at
    # shops and rest sites, which are map features and explicitly out of
    # scope for a combat-only replica, so this is recorded faithfully from
    # the wiki data and deliberately does nothing today. Kept rather than
    # dropped so the card data stays true and so the flag is already right
    # if deck editing is ever added.
    eternal: bool = False
    # Extra play condition beyond cost, as playable_if(card, player) -> bool.
    # Clash ("Can only be played if every card in your Hand is an Attack") is
    # the only Colorless user, but gating inside the effect instead would let
    # the play succeed and burn the energy before fizzling.
    playable_if: Optional[Callable] = None

    def __post_init__(self):
        if not self.rarity:
            self.rarity = rarity_for_card(self.name, self.card_type)

    def val(self, key: str, default: int = 0) -> int:
        """Read a numeric value, honoring upgrade state."""
        if self.upgraded and key in self.upgrade_values:
            return self.upgrade_values[key]
        return self.values.get(key, default)

    def current_cost(self, player=None) -> Union[int, str]:
        """Read effective energy cost, honoring upgrade state and -- when a
        player is supplied -- combat state.

        `player` is optional so every existing caller that just wants the
        printed cost keeps working unchanged. Callers that gate on
        affordability (play_card, playable_cards, the UI menus, the bench
        policy) pass it, since a card whose cost drops to 0 mid-turn is
        otherwise shown and rejected as unaffordable.

        Order matters: the card's own dynamic cost resolves first, then
        player-wide overrides win outright, since "Skills cost 0" and "the
        next Attack costs 0" are absolute, not further reductions."""
        base = self.cost
        if self.upgraded and self.upgrade_cost is not None:
            base = self.upgrade_cost
        if player is None or base == "X":
            return base
        if self.dynamic_cost is not None:
            base = self.dynamic_cost(self, player)
        if self.temp_cost is not None:
            base = self.temp_cost
        # Tangled: "Attacks cost an additional energy for 2 turns." The
        # StatusType has existed unwired since early on, waiting for exactly
        # this system. Applied before the zero-cost overrides so a genuinely
        # free Attack stays free.
        if self.card_type == CardType.ATTACK and player.get_status(StatusType.TANGLED) > 0:
            base += 1
        if self.card_type == CardType.SKILL and player.skills_cost_zero:
            base = 0
        if self.card_type == CardType.ATTACK and player.next_attack_free:
            base = 0
        return max(0, base)

    def is_innate(self) -> bool:
        return self.innate or (self.upgraded and self.innate_on_upgrade)

    def upgrade(self):
        self.upgraded = True

    def clone(self) -> "Card":
        """An independent copy, for cards that add a copy of themselves
        (Anger, Outrage). copy.copy() alone is a shallow copy: the clone
        would keep sharing the SAME `values`/`upgrade_values` dict objects
        as the original, so any future per-instance number tweak would
        silently write through to both. Nothing mutates those dicts today,
        but that is exactly the aliasing shape as the dataclass-equality
        bug fixed earlier, so the copies are made explicitly here."""
        twin = copy.copy(self)
        twin.values = dict(self.values)
        twin.upgrade_values = dict(self.upgrade_values)
        return twin

    def exhausts_now(self) -> bool:
        """Whether THIS printing (base or upgraded) exhausts. A few real
        cards (Demonic Shield) lose the Exhaust keyword on upgrade."""
        if self.upgraded and self.loses_exhaust_on_upgrade:
            return False
        return self.exhausts

    def retains_now(self) -> bool:
        """Whether THIS printing has Retain."""
        return self.retain or (self.upgraded and self.retain_on_upgrade)

    def is_ethereal(self) -> bool:
        """Whether THIS printing has Ethereal."""
        if self.upgraded and self.loses_ethereal_on_upgrade:
            return False
        return self.ethereal

    def is_unplayable(self) -> bool:
        """Statuses and Curses whose text is '$Unplayable'. The wiki encodes
        these as Cost = -2; this replica uses UNPLAYABLE (999) so the ordinary
        'can you afford it' check in playable_cards/play_card rejects them
        with no special case, and so a stray cost reduction can never make
        one castable."""
        return self.cost == UNPLAYABLE

    def current_description(self) -> str:
        if self.upgraded and self.upgraded_description:
            return self.upgraded_description
        return self.description

    def __repr__(self):
        current = self.current_cost()
        cost_str = "X" if current == "X" else str(current)
        name = self.name + "+" if self.upgraded else self.name
        return f"<Card {name} ({cost_str})>"


