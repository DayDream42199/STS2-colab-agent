def fx_cascade(engine, caster, target, card, **kwargs):
    """X-cost: play the top X (or X+1 upgraded) cards of the Draw Pile,
    reusing Havoc's play-the-top-card logic per card played."""
    times = kwargs.get("x_amount", 0)
    if card.upgraded:
        times += 1
    for _ in range(times):
        played = caster.take_top_of_draw(engine.log)
        if played is None:
            break
        engine.log.append(f"{card.name} plays {played.name} from the draw pile")
        resolvable, auto_target = _auto_target_for(engine, caster, played)
        if resolvable:
            engine.resolve_card_effect(caster, played, auto_target)
        else:
            # Every remaining iteration would find the same empty board, so
            # stop drawing rather than milling the rest of X for nothing.
            engine.log.append(f"{played.name} has nothing left to hit")
            caster.discard_pile.append(played)
            break
        if played.exhausts_now():
            engine.exhaust_card(caster, played)
        else:
            caster.discard_pile.append(played)


