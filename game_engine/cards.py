def make_ironclad_pool_deck() -> List[Card]:
    """One fresh copy of every ported real Ironclad card -- useful for
    testing/demoing the full ported set, not a realistic starting deck."""
    return [factory() for factory in CARD_POOL_IRONCLAD]


# card_type -> [factory, ...], built once at import. Callers that need "a
# random Attack" (Infernal Blade, the Attack/Skill/Power Potions) used to
# filter the pool with `[f for f in CARD_POOL_IRONCLAD if f().card_type == X]`,
# which instantiated all 60+ cards on every single play just to read one
# field off each. Same result, built once instead of per-play.
FACTORIES_BY_TYPE: Dict[CardType, List[Callable[[], Card]]] = {}
FACTORIES_BY_RARITY: Dict[str, List[Callable[[], Card]]] = {}
for _factory in CARD_POOL_IRONCLAD:
    _sample = _factory()
    FACTORIES_BY_TYPE.setdefault(_sample.card_type, []).append(_factory)
    FACTORIES_BY_RARITY.setdefault(_sample.rarity, []).append(_factory)
del _factory, _sample


def _assert_rarity_coverage():
    """Guard the 'unlisted == Uncommon' default in rarity_for_card(). If a
    newly-ported card is missing from the Common/Rare tables it silently
    becomes Uncommon, which would quietly skew any rarity-weighted reward
    (White Star's Rare-only drop being the first). Basic cards never enter
    the pool, and Status cards are never rewards, so neither belongs here."""
    tiers = {r: len(v) for r, v in FACTORIES_BY_RARITY.items()}
    unexpected = set(tiers) - {"Common", "Uncommon", "Rare"}
    assert not unexpected, f"unexpected rarity tier in the card pool: {unexpected}"
    assert tiers.get("Common") == len(_COMMON_CARDS), (
        f"expected all {len(_COMMON_CARDS)} Common cards in the pool, found {tiers.get('Common')}")


_assert_rarity_coverage()


# ---------------------------------------------------------------------------
# Stable card ids, for anything that wants to identify a card numerically --
# principally env.py, whose observation has to describe the hand its action
# space indexes into.
#
# Sorted by name so the mapping is deterministic across runs and processes
# (dict-insertion or set-iteration order would not be). Adding a new card
# DOES renumber everything after it alphabetically, so a trained embedding
# table is only valid against the pool it was trained on -- fine here, worth
# knowing before persisting ids anywhere.
# ---------------------------------------------------------------------------

def _all_card_names() -> List[str]:
    names = set()
    for pool in (CARD_POOL_IRONCLAD, ANCIENT_CARDS_IRONCLAD, COLORLESS_POOL,
                 ANCIENT_COLORLESS, CURSE_POOL):
        names |= {f().name for f in pool}
    names |= {mk().name for mk in STATUS_CARDS}
    names |= {c.name for c in make_starter_deck()}
    # The one-off makers: statuses enemies hand out, plus Primal Force's token.
    for fn in (make_wound, make_infection, make_dazed, make_slimed, make_beckon,
               make_toxic, make_burn, make_frantic_escape, make_giant_rock,
               make_wither):
        names.add(fn().name)
    return sorted(names)


CARD_IDS: Dict[str, int] = {name: i for i, name in enumerate(_all_card_names())}
TOTAL_CARD_IDS = len(CARD_IDS)


def card_id(card: "Card") -> int:
    """Stable id for a card, or -1 if it is not a known printing. -1 rather
    than a KeyError because a card built ad hoc by a test or an enemy effect
    should degrade to "unknown" instead of crashing an observation."""
    return CARD_IDS.get(card.name, -1)
