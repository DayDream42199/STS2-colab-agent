# The rest of the Colorless module (#39).
#
# The module has 151 entries. 32 were already here (the 22-card pool above
# plus the statuses enemies hand out), 16 are permanently out of scope, and
# these are the remaining 103. Scope calls, all recorded rather than silent:
#
#   * Quest cards (Byrdonis Egg, Lantern Key, Spoils Map, Dowsing) are map
#     items with no combat text -- excluded.
#   * Other characters' tokens (Shiv, Soul, Fuel, Luminesce, Sovereign
#     Blade, the three Minion cards) and Splash ("an Attack from another
#     character") need classes that will never exist here -- excluded.
#     Sweeping Gaze goes with them: its text is "Osty deals X damage", and
#     Osty is another character's companion.
#   * "Mad Science" itself is a placeholder whose text is only "This card
#     can be created and customized at the event Tinker Time" -- excluded.
#     Its nine CUSTOMISED printings all have real, self-contained combat
#     text, so those ARE ported.
#   * "Wither (Upgraded)" is a NoList duplicate of Wither, already ported.
#   * Gold clauses are dropped, the combat half kept: Hand of Greed loses
#     "if Fatal, gain 20 Gold", Debt loses "lose 10 Gold". Both are noted on
#     the cards themselves.
#
# Two engine conventions used throughout, both pre-existing:
#   "Choose 1 of 3 ..." is resolved as a RANDOM pick. This replica has no
#   card-choice interface anywhere (Discovery, Abundance, Wish, Scrawl,
#   Seeker Strike and Stratagem all want one), and inventing a prompt only
#   for Colorless would leave the ~8 Ironclad cards of the same shape
#   inconsistent. Every such card says so in its docstring.
#   "It's free to play this turn" builds a FRESH Card instance with cost 0
#   rather than discounting a deck card, because a card in hand is the same
#   object as the one in deck_template -- see Player.set_temp_cost.
# ===========================================================================

def _fresh_free_card(caster, factory):
    """A brand-new card instance, free this turn, safe to mutate.

    Never touches deck_template, so forcing `cost = 0` on it cannot leak
    into the next combat -- the aliasing trap documented on
    Player.upgrade_for_combat."""
    c = factory()
    c.cost = 0
    return c


def _pick(caster, seq):
    return caster.rng.choice(list(seq)) if seq else None


def _sample_distinct(caster, seq, n):
    """Up to n DISTINCT entries, for the "choose 1 of 3" cards. Distinct
    matters: offering the same card three times is not a choice.

    NOT named `_sample`: the pool-index loop at the bottom of this file uses
    `_sample` as a throwaway and ends with `del _factory, _sample`, which
    deleted this function at import time and turned every "choose 1 of 3"
    card into a NameError."""
    seq = list(seq)
    if len(seq) <= n:
        return seq
    idx = caster.rng.sample(range(len(seq)), n)
    return [seq[i] for i in idx]


def _ally_of(engine, caster):
    """The ally a Multiplayer card acts on, or None when playing solo."""
    return engine.other_player(caster)


