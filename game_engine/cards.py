def make_wound() -> Card:
    """A curse-adjacent Status card, shuffled into a player's discard pile
    by enemy effects (e.g. Vantom's Dismember). Real STS Wound is
    "Unplayable" -- rather than adding a new Card field just for this,
    its cost (999) already makes playable_cards()'s `cost <= energy`
    filter exclude it unconditionally, same observable effect with zero
    engine changes."""
    return Card("Wound", 999, CardType.STATUS, TargetMode.SELF, lambda *a, **kw: None,
                description="Unplayable.", upgraded_description="Unplayable.")


