def make_frantic_escape() -> Card:
    """The Insatiable's status card: "Get farther away. Increase Sandpit by
    1. Increase the cost of this card by 1." Unlike every other Status here
    it is PLAYABLE and you want to play it -- it is the escape hatch from
    the Sandpit countdown, and it gets more expensive each time."""
    def _fx(engine, caster, target, card, **kwargs):
        caster.add_status(StatusType.SANDPIT, 1)
        # Through set_temp_cost, NOT `card.cost += 1`. In practice The
        # Insatiable shuffles fresh instances into the draw/discard pile and
        # they die with the combat, so writing `cost` directly happened to be
        # harmless -- but a card in deck_template IS the object in hand, so
        # that spelling is one reward-screen away from permanently inflating
        # a real deck card. The escalation is identical either way; this one
        # reverts at combat end.
        raised = card.current_cost(caster) + 1
        caster.set_temp_cost(card, raised, scope="combat")
        engine.log.append(
            f"{caster.name} scrambles free: Sandpit up to "
            f"{caster.get_status(StatusType.SANDPIT)}, card now costs {raised}")
    return Card("Frantic Escape", 1, CardType.STATUS, TargetMode.SELF, _fx,
                description="Get farther away. Increase Sandpit by 1. Increase the cost of this card by 1.",
                upgraded_description="Get farther away. Increase Sandpit by 1. Increase the cost of this card by 1.")


